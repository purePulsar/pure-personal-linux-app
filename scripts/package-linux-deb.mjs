#!/usr/bin/env node
/**
 * Build a Debian package from the electron-builder linux-unpacked directory.
 *
 * electron-builder's bundled fpm can be slow or unavailable in constrained
 * environments; this script produces the same install layout with the native
 * dpkg-deb toolchain: /usr/lib/dsh-desktop, /usr/bin/dsh-desktop, desktop
 * entry, hicolor icon, AppArmor profile and a chrome-sandbox setuid postinst.
 */

import { chmodSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { spawnSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const unpackedRoot = join(packageRoot, 'dist', 'linux-unpacked')
const stagingRoot = join(packageRoot, 'dist', 'deb-staging')
const outputDir = join(packageRoot, 'dist')

const manifest = JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8'))
const version = manifest.version
const artifactName = `DSH-Desktop-${version}-amd64.deb`
const packageName = 'dsh-desktop'
const installRoot = `/usr/lib/${packageName}`

function run(command, args, cwd = packageRoot) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' })
  if (result.error !== undefined) throw result.error
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} exited with ${String(result.status)}`)
  }
}

function main() {
  if (!existsSync(join(unpackedRoot, packageName))) {
    throw new Error(`linux-unpacked application missing at ${unpackedRoot}; run "yarn workspace dsh-plugin-desktop package:dir" first`)
  }

  rmSync(stagingRoot, { recursive: true, force: true })
  const debianRoot = join(stagingRoot, 'DEBIAN')
  const appRoot = join(stagingRoot, installRoot.slice(1))
  const binDir = join(stagingRoot, 'usr', 'bin')
  const applicationsDir = join(stagingRoot, 'usr', 'share', 'applications')
  const iconDir = join(stagingRoot, 'usr', 'share', 'icons', 'hicolor', '512x512', 'apps')
  const apparmorDir = join(stagingRoot, 'etc', 'apparmor.d')
  mkdirSync(debianRoot, { recursive: true })
  mkdirSync(appRoot, { recursive: true })
  mkdirSync(binDir, { recursive: true })
  mkdirSync(applicationsDir, { recursive: true })
  mkdirSync(iconDir, { recursive: true })
  mkdirSync(apparmorDir, { recursive: true })

  // Application payload: everything electron-builder placed in linux-unpacked.
  cpSync(unpackedRoot, appRoot, { recursive: true })

  // /usr/bin/dsh-desktop -> /usr/lib/dsh-desktop/dsh-desktop
  const binLink = join(binDir, packageName)
  if (existsSync(binLink)) rmSync(binLink)
  writeFileSync(binLink, `#!/bin/sh\nexec ${installRoot}/dsh-desktop "$@"\n`)
  chmodSync(binLink, 0o755)

  // Desktop entry.
  writeFileSync(join(applicationsDir, `${packageName}.desktop`), [
    '[Desktop Entry]',
    'Name=DSH Desktop',
    'Comment=DeepSeek Harness desktop client',
    `Exec=${installRoot}/dsh-desktop`,
    'Terminal=false',
    'Type=Application',
    'Icon=dsh-desktop',
    'Categories=Development;Utility;',
    'StartupWMClass=dsh-desktop',
    '',
  ].join('\n'))

  // hicolor icon.
  cpSync(join(packageRoot, 'build', 'app-icon.png'), join(iconDir, `${packageName}.png`))

  // AppArmor profile generated by electron-builder (may be absent).
  const apparmorProfile = join(unpackedRoot, 'apparmor-profile')
  if (existsSync(apparmorProfile)) {
    cpSync(apparmorProfile, join(apparmorDir, packageName))
  }

  // Control metadata. Depends covers the libraries the packaged binary links.
  writeFileSync(join(debianRoot, 'control'), [
    `Package: ${packageName}`,
    `Version: ${version}`,
    'Section: devel',
    'Priority: optional',
    'Architecture: amd64',
    `Maintainer: ${manifest.build?.linux?.maintainer ?? 'DSH Desktop Linux Maintainers <dsh-desktop@localhost>'}`,
    'Installed-Size: 600000',
    'Depends: libgtk-3-0 (>= 3.24), libnss3, libasound2t64 | libasound2, libgbm1, libxss1, libxtst6, libatspi2.0-0, libuuid1, libsecret-1-0, xdg-utils',
    'Description: DSH Desktop - DeepSeek Harness desktop client',
    ' DSH Desktop brings the DeepSeek Harness local Web UI, Host service, and',
    ' plugin system into a native Linux desktop application: desktop window,',
    ' system tray, profile management and the official plugin ecosystem.',
    '',
  ].join('\n'))

  // postinst: make the Chromium sandbox helper setuid root.
  writeFileSync(join(debianRoot, 'postinst'), [
    '#!/bin/sh',
    'set -e',
    `chown root:root ${installRoot}/chrome-sandbox || true`,
    `chmod 4755 ${installRoot}/chrome-sandbox || true`,
    'exit 0',
    '',
  ].join('\n'))
  chmodSync(join(debianRoot, 'postinst'), 0o755)

  const output = join(outputDir, artifactName)
  rmSync(output, { force: true })
  run('fakeroot', ['dpkg-deb', '--build', '--root-owner-group', stagingRoot, output])
  rmSync(stagingRoot, { recursive: true, force: true })
  console.log(`Built ${output}`)
}

main()
